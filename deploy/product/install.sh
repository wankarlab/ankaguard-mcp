#!/usr/bin/env bash
# Installer of the product stack (OpenSpec task 10.6, design D14).
#
# Generates deploy/product/.env with random secrets the first time and NEVER
# overwrites an existing one. It never prints secret values. It does not start
# anything: afterwards run `docker compose up -d --build`.
#
#   ./install.sh [target-dir]      (default: the directory of this script)
set -euo pipefail

HERE="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
TARGET="${1:-$HERE}"
ENV_FILE="$TARGET/.env"

command -v openssl >/dev/null 2>&1 || { echo "install: openssl is required to generate secrets" >&2; exit 1; }
[ -d "$TARGET" ] || { echo "install: target directory does not exist: $TARGET" >&2; exit 1; }

if [ -e "$ENV_FILE" ]; then
  echo "install: $ENV_FILE already exists; leaving it untouched (secrets and data are preserved)."
  echo "install: next step: docker compose up -d --build"
  exit 0
fi

hex()  { openssl rand -hex "$1"; }
b64()  { openssl rand -base64 "$1"; }

# Create the file private from the start (no window with permissive modes).
umask 077
tmp="$(mktemp "$TARGET/.env.XXXXXX")"
trap 'rm -f "$tmp"' EXIT
{
  echo "# Generated by install.sh. Contains secrets: do not commit or share."
  echo "# Edition: product,pro = Community + Pro components; product = Community only."
  echo "EDITION_TAGS=product,pro"
  echo "SERVER_PORT=10600"
  echo "CONSOLE_PORT=3002"
  echo
  echo "# GoCryptoTrader gRPC credentials (shared by the server and the daemon)"
  echo "GCT_USERNAME=gct"
  echo "GCT_PASSWORD=$(hex 24)"
  echo
  echo "# Postgres of the runtime configuration"
  echo "TRADING_CONFIG_DB_PASSWORD=$(hex 24)"
  echo
  echo "# Encryption keys (base64, 32 bytes). Losing them makes stored credentials unreadable."
  echo "CREDENTIAL_ENCRYPTION_KEY=$(b64 32)"
  echo "CONFIG_ENCRYPTION_KEY=$(b64 32)"
  echo
  echo "# Token of the /admin/config endpoints"
  echo "ADMIN_API_TOKEN=$(hex 32)"
  echo
  echo "# Pro license (paste the key you received, or leave empty for Community)"
  echo "LICENSE_KEY="
} > "$tmp"

# Atomic and race-safe: link fails if .env appeared meanwhile, so it is never overwritten.
if ln "$tmp" "$ENV_FILE" 2>/dev/null; then
  chmod 600 "$ENV_FILE"
  echo "install: created $ENV_FILE with random secrets (mode 600; values not shown)."
else
  echo "install: $ENV_FILE appeared while installing; leaving it untouched."
fi
echo "install: next step: docker compose up -d --build"
echo "install: then set the operator password: docker compose exec server trading-mcp-server -config /app/configs/product/config.yaml operator set-password"
