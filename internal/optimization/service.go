package optimization

import (
	"context"
	"encoding/json"
	"fmt"
	"time"

	"github.com/sirupsen/logrus"

	backtestCore "github.com/rantipay/trading-mcp/internal/backtest"
	backtestdomain "github.com/rantipay/trading-mcp/internal/backtest/domain"
	configdomain "github.com/rantipay/trading-mcp/internal/config/dynamic/domain"
	configrepo "github.com/rantipay/trading-mcp/internal/config/dynamic/repository"
	optdomain "github.com/rantipay/trading-mcp/internal/optimization/domain"
	optrepo "github.com/rantipay/trading-mcp/internal/optimization/repository"
)

// OptimizeRequest describes a single optimization job.
type OptimizeRequest struct {
	Space        ParamSpace
	SpaceName    string // human-readable name stored in the run record
	ObjectiveName string
	Objective    Objective
	Pair         string
	Exchange     string
	HorizonFrom  time.Time
	HorizonTo    time.Time
	Iterations   int
	By           string // actor identifier (user / scheduler)
}

// OptimizeResult summarises a completed optimization run.
type OptimizeResult struct {
	RunID      int64
	BestScore  float64
	TopPresets []string // names of auto-generated presets
	History    []TrialResult
}

// OptimizerService orchestrates parameter search by running the backtest engine
// across many parameter combinations and persisting the results.
type OptimizerService struct {
	btEngine *backtestCore.Engine
	cfgRepo  configrepo.ConfigRepository
	optRepo  optrepo.OptimizerRepository
	log      *logrus.Logger
}

// NewOptimizerService creates an OptimizerService.
func NewOptimizerService(
	btEngine *backtestCore.Engine,
	cfgRepo configrepo.ConfigRepository,
	optRepo optrepo.OptimizerRepository,
	log *logrus.Logger,
) *OptimizerService {
	return &OptimizerService{
		btEngine: btEngine,
		cfgRepo:  cfgRepo,
		optRepo:  optRepo,
		log:      log,
	}
}

// Run executes an optimization job synchronously.
// It should be called from a goroutine when triggered via API to avoid blocking.
func (s *OptimizerService) Run(ctx context.Context, runID int64, req OptimizeRequest) (*OptimizeResult, error) {
	log := s.log.WithFields(logrus.Fields{
		"run_id":     runID,
		"pair":       req.Pair,
		"iterations": req.Iterations,
		"objective":  req.ObjectiveName,
	})

	// Mark run as in-progress.
	if err := s.optRepo.MarkRunning(ctx, runID); err != nil {
		return nil, fmt.Errorf("mark running: %w", err)
	}

	opt := NewBayesianOptimizer()
	var history []TrialResult

	for i := 0; i < req.Iterations; i++ {
		select {
		case <-ctx.Done():
			_ = s.optRepo.MarkFailed(ctx, runID, "cancelled: context done")
			return nil, ctx.Err()
		default:
		}

		// 1. Optimizer suggests next parameter combination.
		params, err := opt.Suggest(ctx, req.Space, history)
		if err != nil {
			log.WithError(err).Warn("optimizer: suggest failed, skipping iteration")
			continue
		}

		// 2. Run backtest with those overrides.
		btReq := backtestdomain.BacktestRequest{
			Overrides:   params,
			Pair:        req.Pair,
			Exchange:    req.Exchange,
			From:        req.HorizonFrom,
			To:          req.HorizonTo,
			TriggeredBy: fmt.Sprintf("optimizer:run%d", runID),
		}
		btResult, err := s.btEngine.Run(ctx, btReq)
		if err != nil {
			log.WithError(err).WithField("iteration", i).Warn("backtest failed, skipping trial")
			continue
		}

		// 3. Evaluate objective.
		obj := req.Objective(btResult.Metrics)
		trial := TrialResult{Params: params, Objective: obj}
		history = append(history, trial)

		// 4. Persist trial.
		metricsJSON, _ := json.Marshal(btResult.Metrics)
		if tErr := s.optRepo.InsertTrial(ctx, &optdomain.OptimizerTrial{
			RunID:     runID,
			Iteration: i,
			Params:    params,
			Metrics:   json.RawMessage(metricsJSON),
			Objective: obj,
		}); tErr != nil {
			log.WithError(tErr).Warn("failed to persist trial")
		}

		log.WithFields(logrus.Fields{
			"iteration": i,
			"objective": obj,
			"n_trades":  btResult.Metrics.NTrades,
		}).Debug("optimizer: trial completed")
	}

	// 5. Select top-3 and generate auto-presets (inactive, for human review).
	top3 := SelectTopN(history, 3)
	presetNames := make([]string, 0, len(top3))
	bestScore := 0.0

	for i, t := range top3 {
		if i == 0 {
			bestScore = t.Objective
		}
		presetName := fmt.Sprintf("_auto_%s_opt%d_top%d", sanitizePair(req.Pair), runID, i+1)
		paramsJSON, _ := json.Marshal(t.Params)

		preset := &configdomain.ParameterPreset{
			Name:        presetName,
			Description: fmt.Sprintf("Auto-generated by optimizer run %d (rank %d/%d). Objective=%s score=%.4f", runID, i+1, len(top3), req.ObjectiveName, t.Objective),
			ScopeType:   configdomain.ScopeGlobal,
			ScopeID:     "*",
			ParamsJSON:  json.RawMessage(paramsJSON),
			CreatedBy:   "optimizer",
			IsActive:    false,
		}

		if pErr := s.cfgRepo.CreatePreset(ctx, preset); pErr != nil {
			log.WithError(pErr).WithField("preset", presetName).Warn("failed to persist auto-preset")
			continue
		}
		presetNames = append(presetNames, presetName)
		log.WithField("preset", presetName).WithField("score", t.Objective).Info("optimizer: auto-preset created (inactive, pending human review)")
	}

	// 6. Mark run done.
	if err := s.optRepo.MarkDone(ctx, runID, bestScore, presetNames); err != nil {
		log.WithError(err).Warn("failed to mark optimizer run done")
	}

	log.WithFields(logrus.Fields{
		"trials":      len(history),
		"top_presets": presetNames,
		"best_score":  bestScore,
	}).Info("optimizer: run finished")

	return &OptimizeResult{
		RunID:      runID,
		BestScore:  bestScore,
		TopPresets: presetNames,
		History:    history,
	}, nil
}

// sanitizePair replaces '/' with '-' so preset names are valid identifiers.
func sanitizePair(pair string) string {
	out := []byte(pair)
	for i, c := range out {
		if c == '/' {
			out[i] = '-'
		}
	}
	return string(out)
}
