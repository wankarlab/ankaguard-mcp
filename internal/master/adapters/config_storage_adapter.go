package adapters

import (
	"encoding/json"
	"fmt"
	"time"

	"github.com/sirupsen/logrus"

	"github.com/rantipay/trading-mcp/internal/master"
	"github.com/rantipay/trading-mcp/internal/storage"
)

// ConfigStorageAdapter persists master.GeneratedConfig values into the
// trading_profiles table. The full GeneratedConfig is serialised to JSON and
// written into the existing config column, keyed by name "master:<pair>".
//
// Each pair has a single live row — subsequent saves overwrite the previous
// one (Upsert). To inspect history, query the trade ledger or enable
// snapshotting separately.
type ConfigStorageAdapter struct {
	log  *logrus.Logger
	repo *storage.TradingProfilesRepository
}

// NewConfigStorageAdapter wires a TradingProfilesRepository to the
// master.ConfigStorage interface.
func NewConfigStorageAdapter(log *logrus.Logger, repo *storage.TradingProfilesRepository) *ConfigStorageAdapter {
	if log == nil {
		log = logrus.New()
	}
	return &ConfigStorageAdapter{
		log:  log,
		repo: repo,
	}
}

// profileName returns the canonical trading_profiles.name for a given pair.
func profileName(pair string) string {
	return fmt.Sprintf("master:%s", pair)
}

// SaveGeneratedConfig stores the config under name "master:<pair>". Existing
// rows for the same pair are replaced via Upsert.
func (c *ConfigStorageAdapter) SaveGeneratedConfig(pair string, config *master.GeneratedConfig) error {
	if c == nil || c.repo == nil {
		return fmt.Errorf("config storage adapter not initialised")
	}
	if config == nil {
		return fmt.Errorf("config is nil")
	}
	if pair == "" {
		return fmt.Errorf("pair is required")
	}

	body, err := json.Marshal(config)
	if err != nil {
		return fmt.Errorf("failed to marshal generated config for %s: %w", pair, err)
	}

	tags, _ := json.Marshal([]string{"master_agent", config.Regime})

	return c.repo.Upsert(&storage.TradingProfile{
		Name:        profileName(pair),
		Description: fmt.Sprintf("Auto-generated by master agent for %s (regime=%s)", pair, config.Regime),
		Config:      string(body),
		IsDefault:   false,
		Tags:        string(tags),
		CreatedBy:   "master_agent",
		UpdatedAt:   time.Now(),
	})
}

// LoadLatestConfig retrieves the most recent persisted config for a pair.
// Returns (nil, nil) when no row exists.
func (c *ConfigStorageAdapter) LoadLatestConfig(pair string) (*master.GeneratedConfig, error) {
	if c == nil || c.repo == nil {
		return nil, fmt.Errorf("config storage adapter not initialised")
	}
	if pair == "" {
		return nil, fmt.Errorf("pair is required")
	}

	profile, err := c.repo.GetByName(profileName(pair))
	if err != nil {
		return nil, fmt.Errorf("failed to load profile for %s: %w", pair, err)
	}
	if profile == nil {
		return nil, nil
	}

	var config master.GeneratedConfig
	if err := json.Unmarshal([]byte(profile.Config), &config); err != nil {
		return nil, fmt.Errorf("failed to unmarshal config for %s: %w", pair, err)
	}

	return &config, nil
}

// Compile-time assertion: the adapter satisfies master.ConfigStorage.
var _ master.ConfigStorage = (*ConfigStorageAdapter)(nil)
