package master

import (
	"context"
	"time"

	"github.com/rantipay/trading-mcp/internal/ai"
	"github.com/rantipay/trading-mcp/internal/ai/regime"
	"github.com/rantipay/trading-mcp/internal/services"
)

// MarketOpportunity is an opportunity detected by the scanner.
type MarketOpportunity struct {
	Pair              string
	Exchange          string
	OpportunityScore  float64
	Volatility        float64
	Volume24hUSD      float64
	TrendStrength     float64
	SentimentScore    float64
	BTCCorrelation    float64
	RegimeMatch       float64
	RecentLossPenalty float64
	ProfitFactor      float64 // expectancy %/trade scaled to score points; + bonus, - penalty
	Reasoning         string
	DetectedAt        time.Time

	// CachedAnalysis holds the regime analysis produced by the scanner so
	// the master-agent tick can reuse it for config generation without a
	// second (redundant) GetCandles + Analyze round-trip. nil when the
	// scanner did not populate it (backward-compatible).
	CachedAnalysis *regime.RegimeAnalysis
}

// GeneratedConfig is the configuration generated by the Master for a pair.
type GeneratedConfig struct {
	Pair            string
	Exchange        string
	GeneratedBy     string
	GeneratedAt     time.Time
	Regime          string
	StrategyWeights map[string]float64
	Timeframes      []string
	IndicatorConfig IndicatorConfig
	RiskConfig      RiskConfig
	LLMConfig       LLMConfig
	FilterConfig    FilterConfig
	Reasoning       string
}

type IndicatorConfig struct {
	RSIPeriod  int
	MACDFast   int
	MACDSlow   int
	MACDSignal int
	ATRPeriod  int
	BBPeriod   int
	BBStdDev   float64
}

type RiskConfig struct {
	MaxPositionSizeUSD      float64
	StopLossATRMultiplier   float64
	TakeProfitATRMultiplier float64
	MaxLeverage             int
	UseTrailingStop         bool
}

type LLMConfig struct {
	ConsensusRequired     bool
	MinConsensusProviders int
	ConfidenceThreshold   float64
}

type FilterConfig struct {
	MinVolume24hUSD     float64
	BTCCorrelationCheck bool
	SentimentCheck      bool
	RegimeCheck         bool
}

// MasterState is a snapshot of the master agent state.
type MasterState struct {
	Running          bool
	StartedAt        time.Time
	LastScanAt       time.Time
	LastScanDuration time.Duration
	ScanCount        int64
	ActiveBots       int
	TotalCapitalUSD  float64
	AllocatedUSD     float64
	Opportunities    []*MarketOpportunity
	Allocations      map[string]*services.AllocationResult
	LastError        string
	// MultiPairEnabled reflects whether bot spawning is active (config.multi_pair.enabled).
	// false = scan-only mode (observe opportunities without spawning).
	MultiPairEnabled bool
	// SpawnThreshold is the minimum score (0-1) required to spawn a bot.
	SpawnThreshold float64
}

// PairFeedback is per-pair aggregated trade feedback.
type PairFeedback struct {
	Pair              string
	TotalTrades       int
	WinningTrades     int
	LosingTrades      int
	WinRate           float64
	AvgWinPercent     float64
	AvgLossPercent    float64
	TotalPnLUSD       float64
	LastTradeAt       time.Time
	RecentLossesCount int
}

// ScoringWeights are mutable scanner weights tuned by the feedback loop.
type ScoringWeights struct {
	Volatility            float64
	Volume                float64
	TrendStrength         float64
	Sentiment             float64
	RegimeMatch           float64
	BTCCorrelationPenalty float64
	RecentLossPenalty     float64
	ProfitFactor          float64 // weight applied to expectancy-per-trade signal
}

// TickerSummary is a minimal ticker view for scanner ranking.
type TickerSummary struct {
	Pair             string
	Exchange         string
	Volume24h        float64
	LastPrice        float64
	Change24hPercent float64
}

// GCTAdapter is the minimal market-data interface required by the scanner.
type GCTAdapter interface {
	GetTopPairsByVolume(ctx context.Context, exchange string, n int) ([]TickerSummary, error)
	GetCandles(ctx context.Context, exchange, pair, interval string, limit int) ([]ai.Candle, error)
}

// RegimeAnalyzer is the minimal regime-detection interface used by the scanner.
type RegimeAnalyzer interface {
	Analyze(candles []ai.Candle) (*regime.RegimeAnalysis, error)
}

// SentimentSource is an optional sentiment-feed interface.
type SentimentSource interface {
	GetSentimentScore(ctx context.Context, pair string) (float64, error)
}

// BTCMonitor is an optional BTC-correlation-feed interface.
type BTCMonitor interface {
	GetCorrelation(pair string) float64
}

// BalanceFetcher provides the deployable USDT balance from the configured exchange.
// The master agent uses this to keep the CapitalAllocator's TotalCapitalUSD accurate
// across restarts and account changes. Implementations must be safe for concurrent use.
type BalanceFetcher interface {
	// GetUSDTBalance returns the total available USDT balance. Returns an error
	// when the exchange is unreachable; callers must fall back gracefully.
	GetUSDTBalance(ctx context.Context, exchange string) (float64, error)
}
